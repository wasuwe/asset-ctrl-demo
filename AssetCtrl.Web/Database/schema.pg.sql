-- Asset Ctrl (.NET) schema for PostgreSQL 10+.
-- Port of asset_ctrl_v2/database/schema.sql (MySQL). Same tables and columns, so data can be copied across.
-- Differences: SERIAL/IDENTITY ids, SMALLINT for 0/1 flags (the code compares them with = 1),
-- TIMESTAMP(0) for DATETIME, and app_sessions for the server-side session.
-- Safe to re-run: every statement uses IF NOT EXISTS.

-- ---------------------------------------------------------------------------
-- Organisation
-- ---------------------------------------------------------------------------
-- Depts are no longer used by the application (users are granted Work Centers directly);
-- kept so data copied from the PHP version is not lost.
CREATE TABLE IF NOT EXISTS departments (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32)  NOT NULL,
    name        VARCHAR(191) NOT NULL DEFAULT '',
    is_active   SMALLINT     NOT NULL DEFAULT 1,
    created_at  TIMESTAMP(0) NOT NULL,
    updated_at  TIMESTAMP(0) NOT NULL,
    CONSTRAINT uq_departments_code UNIQUE (code)
);

-- Work centers come from the master sheet ("2300-ICS" -> code 2300, name ICS).
CREATE TABLE IF NOT EXISTS work_centers (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(16)  NOT NULL,
    name           VARCHAR(191) NOT NULL DEFAULT '',
    department_id  INTEGER      NULL REFERENCES departments (id) ON DELETE SET NULL,
    is_active      SMALLINT     NOT NULL DEFAULT 1,
    created_at     TIMESTAMP(0) NOT NULL,
    updated_at     TIMESTAMP(0) NOT NULL,
    CONSTRAINT uq_work_centers_code UNIQUE (code)
);
CREATE INDEX IF NOT EXISTS ix_work_centers_department ON work_centers (department_id);

-- Master lists for asset fields that hold a code: Type PC, Location, Building / floor.
CREATE TABLE IF NOT EXISTS asset_masters (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(16)  NOT NULL,              -- pc_type | location | building
    code        VARCHAR(64)  NOT NULL,
    name        VARCHAR(191) NOT NULL DEFAULT '',
    is_active   SMALLINT     NOT NULL DEFAULT 1,
    created_at  TIMESTAMP(0) NOT NULL,
    updated_at  TIMESTAMP(0) NOT NULL,
    CONSTRAINT uq_asset_masters UNIQUE (kind, code)
);

-- ---------------------------------------------------------------------------
-- Users & access
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_code              VARCHAR(32)  NOT NULL,          -- login id
    first_name            VARCHAR(100) NOT NULL,
    last_name             VARCHAR(100) NOT NULL DEFAULT '',
    email                 VARCHAR(191) NULL,
    phone                 VARCHAR(32)  NULL,
    department_id         INTEGER      NULL REFERENCES departments (id) ON DELETE SET NULL,
    role                  VARCHAR(16)  NOT NULL DEFAULT 'user',    -- admin | user
    can_repair            SMALLINT     NOT NULL DEFAULT 0,
    password_hash         VARCHAR(255) NOT NULL,
    must_change_password  SMALLINT     NOT NULL DEFAULT 1,
    is_active             SMALLINT     NOT NULL DEFAULT 1,
    failed_logins         SMALLINT     NOT NULL DEFAULT 0,
    locked_until          TIMESTAMP(0) NULL,
    last_login_at         TIMESTAMP(0) NULL,
    created_at            TIMESTAMP(0) NOT NULL,
    updated_at            TIMESTAMP(0) NOT NULL,
    CONSTRAINT uq_users_emp_code UNIQUE (emp_code)
);
CREATE INDEX IF NOT EXISTS ix_users_role ON users (role);

CREATE TABLE IF NOT EXISTS user_departments (
    user_id        INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    department_id  INTEGER NOT NULL REFERENCES departments (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, department_id)
);

-- Work Centers a user may see (one user can have many). The only access scope for users.
CREATE TABLE IF NOT EXISTS user_work_centers (
    user_id         INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    work_center_id  INTEGER NOT NULL REFERENCES work_centers (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, work_center_id)
);

-- ---------------------------------------------------------------------------
-- Assets
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS assets (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_no        VARCHAR(32)  NOT NULL,           -- IT asset number, e.g. PCS142973
    asset_type      VARCHAR(8)   NOT NULL DEFAULT '',-- leading letters of asset_no
    fix_no          VARCHAR(64)  NOT NULL DEFAULT '',-- accounting fixed-asset number
    description     VARCHAR(255) NOT NULL DEFAULT '',
    os_name         VARCHAR(64)  NOT NULL DEFAULT '',
    os_version      VARCHAR(64)  NOT NULL DEFAULT '',
    work_center_id  INTEGER      NULL REFERENCES work_centers (id) ON DELETE SET NULL,
    pc_type         VARCHAR(64)  NOT NULL DEFAULT '',
    location        VARCHAR(32)  NOT NULL DEFAULT '',
    building        VARCHAR(64)  NOT NULL DEFAULT '',
    area            VARCHAR(191) NOT NULL DEFAULT '',
    remark          VARCHAR(255) NOT NULL DEFAULT '',
    status          VARCHAR(16)  NOT NULL DEFAULT '',-- USE SPARE STOCK REPAIR FAIL DISPOSE LOST ('' = unknown)
    last_use        VARCHAR(64)  NOT NULL DEFAULT '',
    editor_note     VARCHAR(128) NOT NULL DEFAULT '',
    mac_address     VARCHAR(64)  NOT NULL DEFAULT '',
    cpu             VARCHAR(128) NOT NULL DEFAULT '',
    ram             VARCHAR(32)  NOT NULL DEFAULT '',
    brand           VARCHAR(64)  NOT NULL DEFAULT '',
    model           VARCHAR(128) NOT NULL DEFAULT '',
    created_at      TIMESTAMP(0) NOT NULL,
    updated_at      TIMESTAMP(0) NOT NULL,
    updated_by      INTEGER      NULL REFERENCES users (id) ON DELETE SET NULL,
    user_checked_at TIMESTAMP(0) NULL,               -- last time a User (department) saved this asset: green/yellow monthly check
    user_checked_by INTEGER      NULL,
    CONSTRAINT uq_assets_asset_no UNIQUE (asset_no)
);
CREATE INDEX IF NOT EXISTS ix_assets_user_checked ON assets (user_checked_at);
CREATE INDEX IF NOT EXISTS ix_assets_work_center ON assets (work_center_id);
CREATE INDEX IF NOT EXISTS ix_assets_status ON assets (status);
CREATE INDEX IF NOT EXISTS ix_assets_type ON assets (asset_type);
CREATE INDEX IF NOT EXISTS ix_assets_location ON assets (location, building);
CREATE INDEX IF NOT EXISTS ix_assets_fix_no ON assets (fix_no);

-- Field-level change log for every asset.
CREATE TABLE IF NOT EXISTS asset_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id    INTEGER      NOT NULL REFERENCES assets (id) ON DELETE CASCADE,
    field       VARCHAR(32)  NOT NULL,              -- column name (work_center = code), or "_created"
    old_value   TEXT NULL,
    new_value   TEXT NULL,
    source      VARCHAR(16)  NOT NULL,              -- edit | bulk | import | repair | audit | migration
    ref_id      INTEGER      NULL,                  -- import batch id / ticket id / audit round id
    note        VARCHAR(255) NULL,
    changed_by  INTEGER      NULL REFERENCES users (id) ON DELETE SET NULL,
    changed_at  TIMESTAMP(0) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_history_asset ON asset_history (asset_id, changed_at);
CREATE INDEX IF NOT EXISTS ix_history_field ON asset_history (field, changed_at);
CREATE INDEX IF NOT EXISTS ix_history_changed_at ON asset_history (changed_at);

-- ---------------------------------------------------------------------------
-- Import (upload -> preview diff -> apply)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS import_batches (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename        VARCHAR(191) NOT NULL,
    file_sha1       CHAR(40)     NOT NULL,
    status          VARCHAR(16)  NOT NULL DEFAULT 'preview',  -- preview | applied | discarded
    total_rows      INTEGER      NOT NULL DEFAULT 0,
    create_count    INTEGER      NOT NULL DEFAULT 0,
    update_count    INTEGER      NOT NULL DEFAULT 0,
    same_count      INTEGER      NOT NULL DEFAULT 0,
    error_count     INTEGER      NOT NULL DEFAULT 0,
    missing_count   INTEGER      NOT NULL DEFAULT 0,
    applied_fields  TEXT NULL,
    uploaded_by     INTEGER      NULL REFERENCES users (id) ON DELETE SET NULL,
    created_at      TIMESTAMP(0) NOT NULL,
    applied_at      TIMESTAMP(0) NULL
);
CREATE INDEX IF NOT EXISTS ix_import_created ON import_batches (created_at);

CREATE TABLE IF NOT EXISTS import_rows (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id   INTEGER      NOT NULL REFERENCES import_batches (id) ON DELETE CASCADE,
    line_no    INTEGER      NOT NULL,
    asset_no   VARCHAR(32)  NOT NULL DEFAULT '',
    action     VARCHAR(8)   NOT NULL,      -- create | update | same | error
    payload    TEXT NOT NULL,
    diff       TEXT NULL,
    message    VARCHAR(255) NULL
);
CREATE INDEX IF NOT EXISTS ix_import_rows_batch ON import_rows (batch_id, action);

-- ---------------------------------------------------------------------------
-- Repair tickets
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS repair_tickets (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_no       VARCHAR(20)  NULL,
    flolites_no     VARCHAR(64)  NOT NULL DEFAULT '',
    asset_id        INTEGER      NULL REFERENCES assets (id) ON DELETE SET NULL,
    asset_no        VARCHAR(32)  NOT NULL DEFAULT '',
    work_center_id  INTEGER      NULL REFERENCES work_centers (id) ON DELETE SET NULL,
    department_id   INTEGER      NULL REFERENCES departments (id) ON DELETE SET NULL,
    reporter_id     INTEGER      NULL REFERENCES users (id) ON DELETE SET NULL,
    contact_name    VARCHAR(100) NOT NULL DEFAULT '',
    contact_phone   VARCHAR(32)  NOT NULL DEFAULT '',
    location_note   VARCHAR(191) NOT NULL DEFAULT '',
    original_area   VARCHAR(191) NOT NULL DEFAULT '',
    received_at     TIMESTAMP(0) NULL,
    returned_at     TIMESTAMP(0) NULL,
    title           VARCHAR(191) NOT NULL,
    symptom         TEXT NOT NULL,
    category        VARCHAR(32)  NOT NULL DEFAULT 'hardware',
    priority        VARCHAR(10)  NOT NULL DEFAULT 'normal',
    status          VARCHAR(16)  NOT NULL DEFAULT 'new',
    assignee_id     INTEGER      NULL REFERENCES users (id) ON DELETE SET NULL,
    resolution      TEXT NULL,
    created_at      TIMESTAMP(0) NOT NULL,
    updated_at      TIMESTAMP(0) NOT NULL,
    assigned_at     TIMESTAMP(0) NULL,
    started_at      TIMESTAMP(0) NULL,
    resolved_at     TIMESTAMP(0) NULL,
    closed_at       TIMESTAMP(0) NULL,
    CONSTRAINT uq_tickets_no UNIQUE (ticket_no)
);
CREATE INDEX IF NOT EXISTS ix_tickets_status ON repair_tickets (status, priority);
CREATE INDEX IF NOT EXISTS ix_tickets_flolites ON repair_tickets (flolites_no);
CREATE INDEX IF NOT EXISTS ix_tickets_assignee ON repair_tickets (assignee_id, status);
CREATE INDEX IF NOT EXISTS ix_tickets_asset ON repair_tickets (asset_id);
CREATE INDEX IF NOT EXISTS ix_tickets_work_center ON repair_tickets (work_center_id);
CREATE INDEX IF NOT EXISTS ix_tickets_department ON repair_tickets (department_id);
CREATE INDEX IF NOT EXISTS ix_tickets_created ON repair_tickets (created_at);
CREATE INDEX IF NOT EXISTS ix_tickets_received ON repair_tickets (received_at, returned_at);
CREATE INDEX IF NOT EXISTS ix_tickets_status_created ON repair_tickets (status, created_at);
CREATE INDEX IF NOT EXISTS ix_tickets_resolved_at ON repair_tickets (resolved_at);
CREATE INDEX IF NOT EXISTS ix_tickets_closed_at ON repair_tickets (closed_at);
-- PostgreSQL does not index foreign keys by itself; users see the tickets they reported.
CREATE INDEX IF NOT EXISTS ix_tickets_reporter ON repair_tickets (reporter_id);

CREATE TABLE IF NOT EXISTS repair_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   INTEGER      NOT NULL REFERENCES repair_tickets (id) ON DELETE CASCADE,
    user_id     INTEGER      NULL REFERENCES users (id) ON DELETE SET NULL,
    event_type  VARCHAR(16)  NOT NULL,     -- created | assigned | status | note | asset | received | returned | queue_jump
    from_value  VARCHAR(64)  NULL,
    to_value    VARCHAR(64)  NULL,
    note        TEXT NULL,
    created_at  TIMESTAMP(0) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_events_ticket ON repair_events (ticket_id, created_at);
-- Repair queue order (received / queue_jump events).
CREATE INDEX IF NOT EXISTS ix_events_ticket_type ON repair_events (ticket_id, event_type, id);

-- ---------------------------------------------------------------------------
-- Physical audit (stock count)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_rounds (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(191) NOT NULL,
    location    VARCHAR(32)  NOT NULL DEFAULT '',
    started_by  INTEGER      NULL REFERENCES users (id) ON DELETE SET NULL,
    started_at  TIMESTAMP(0) NOT NULL,
    closed_at   TIMESTAMP(0) NULL
);

CREATE TABLE IF NOT EXISTS audit_checks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id    INTEGER      NOT NULL REFERENCES audit_rounds (id) ON DELETE CASCADE,
    asset_id    INTEGER      NOT NULL REFERENCES assets (id) ON DELETE CASCADE,
    result      VARCHAR(16)  NOT NULL DEFAULT 'found',
    network     VARCHAR(8)   NOT NULL DEFAULT '',
    area_found  VARCHAR(191) NOT NULL DEFAULT '',
    note        VARCHAR(255) NOT NULL DEFAULT '',
    checked_by  INTEGER      NULL REFERENCES users (id) ON DELETE SET NULL,
    checked_at  TIMESTAMP(0) NOT NULL,
    CONSTRAINT uq_audit_check UNIQUE (round_id, asset_id)
);

-- ---------------------------------------------------------------------------
-- Server-side sessions (.NET version only)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app_sessions (
    id         CHAR(64)     PRIMARY KEY,
    data       TEXT         NOT NULL,
    last_seen  TIMESTAMP(0) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_app_sessions_last_seen ON app_sessions (last_seen);

-- ---------------------------------------------------------------------------
-- Fast "contains" search on repair tickets (ILIKE '%text%' in the ticket list)
-- ---------------------------------------------------------------------------
-- pg_trgm lets PostgreSQL use an index for ILIKE '%text%' (3 characters or more), so the search box
-- stays fast with hundreds of thousands of tickets. One index per searched column: the list ORs them.
-- pg_trgm is a "trusted" extension (PostgreSQL 13+), so the database owner may install it.
-- Without permission the indexes are skipped and search still works (it reads the whole table).
DO $$
BEGIN
    CREATE EXTENSION IF NOT EXISTS pg_trgm;
EXCEPTION WHEN insufficient_privilege OR undefined_file THEN
    RAISE NOTICE 'pg_trgm not installed (%): ticket search works without its indexes.', SQLERRM;
END $$;

DO $$
DECLARE
    col TEXT;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm') THEN
        FOREACH col IN ARRAY ARRAY['ticket_no', 'flolites_no', 'asset_no', 'title', 'symptom', 'contact_name'] LOOP
            EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON repair_tickets USING gin (%I gin_trgm_ops)', 'ix_tickets_trgm_' || col, col);
        END LOOP;
    END IF;
END $$;
